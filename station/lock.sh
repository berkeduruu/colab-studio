#!/usr/bin/env bash
# Regenerates requirements.lock: the complete, pinned Python environment the GPU runtime installs
# into its own venv (torch family from the PyTorch cu130 index, everything else from PyPI).
# Needs only uv and network access; no GPU, no code from the packages is run (wheels only).
#
#   station/lock.sh
#
# Inputs: ComfyUI's requirements.txt at COMFY_COMMIT (fetched), requirements.extra.in,
# base_constraints.txt and audio_requirements.txt. After regenerating, verify on a real GPU
# (python3 server/tests/gpu_smoke.py) before releasing.
set -Eeuo pipefail
cd "$(dirname "$0")"
COMFY_COMMIT=$(sed -n 's/^COMFY_COMMIT=//p' runtime_setup.sh)
PYTHON_VERSION=$(sed -n 's/^PYTHON_VERSION=//p' runtime_setup.sh)
TMP=$(mktemp -d)
trap 'rm -rf "${TMP}"' EXIT
curl -fsS "https://raw.githubusercontent.com/Comfy-Org/ComfyUI/${COMFY_COMMIT}/requirements.txt" \
  | grep -v -i -E '^(torch|torchvision|torchaudio)$|^#|^$' > "${TMP}/comfyui.in"
uv pip compile "${TMP}/comfyui.in" requirements.extra.in \
  -c base_constraints.txt -c audio_requirements.txt \
  --python-version "${PYTHON_VERSION}" --python-platform x86_64-unknown-linux-gnu \
  --no-build --no-header --no-annotate --emit-index-url \
  --index-url https://download.pytorch.org/whl/cu130 --extra-index-url https://pypi.org/simple \
  --index-strategy unsafe-best-match -o "${TMP}/requirements.lock"
{
  echo "# Generated by station/lock.sh: do not edit. ComfyUI ${COMFY_COMMIT:0:10}, Python ${PYTHON_VERSION}, torch cu130."
  cat "${TMP}/requirements.lock"
} > requirements.lock
echo "wrote station/requirements.lock ($(grep -c '==' requirements.lock) packages)"
